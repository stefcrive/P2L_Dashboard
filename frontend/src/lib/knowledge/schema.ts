export const KNOWLEDGE_SCHEMA_VERSION = 1;

export const KNOWLEDGE_SCHEMA_SQL = `
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE SCHEMA IF NOT EXISTS kb;

CREATE TABLE IF NOT EXISTS kb.schema_migrations (
  version integer PRIMARY KEY,
  description text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kb.sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_path text NOT NULL,
  source_name text NOT NULL,
  sha256 text NOT NULL CHECK (length(sha256) = 64),
  byte_size bigint NOT NULL CHECK (byte_size >= 0),
  modified_at timestamptz,
  format text NOT NULL DEFAULT 'merged_conversation_text',
  language text NOT NULL DEFAULT 'en',
  status text NOT NULL DEFAULT 'indexed'
    CHECK (status IN ('discovered', 'processing', 'indexed', 'warning', 'failed', 'obsolete')),
  message_count integer NOT NULL DEFAULT 0 CHECK (message_count >= 0),
  chunk_count integer NOT NULL DEFAULT 0 CHECK (chunk_count >= 0),
  warning_count integer NOT NULL DEFAULT 0 CHECK (warning_count >= 0),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_path, sha256)
);

CREATE TABLE IF NOT EXISTS kb.ingestion_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL DEFAULT 'queued'
    CHECK (status IN ('queued', 'running', 'paused', 'completed', 'failed', 'cancelled')),
  stage text NOT NULL DEFAULT 'queued'
    CHECK (stage IN ('queued', 'parse', 'clean', 'enrich', 'embed', 'index', 'complete')),
  mode text NOT NULL CHECK (mode IN ('parse_only', 'indexed', 'enriched')),
  source_path text NOT NULL,
  enrichment_model text,
  embedding_model text,
  embedding_dimensions integer NOT NULL DEFAULT 1024 CHECK (embedding_dimensions > 0),
  chunk_target_tokens integer NOT NULL DEFAULT 600 CHECK (chunk_target_tokens BETWEEN 200 AND 1600),
  chunk_overlap_tokens integer NOT NULL DEFAULT 90 CHECK (chunk_overlap_tokens BETWEEN 0 AND 400),
  total_files integer NOT NULL DEFAULT 0 CHECK (total_files >= 0),
  processed_files integer NOT NULL DEFAULT 0 CHECK (processed_files >= 0),
  skipped_files integer NOT NULL DEFAULT 0 CHECK (skipped_files >= 0),
  failed_files integer NOT NULL DEFAULT 0 CHECK (failed_files >= 0),
  total_messages integer NOT NULL DEFAULT 0 CHECK (total_messages >= 0),
  total_chunks integer NOT NULL DEFAULT 0 CHECK (total_chunks >= 0),
  embedded_chunks integer NOT NULL DEFAULT 0 CHECK (embedded_chunks >= 0),
  current_file text,
  last_error text,
  warnings jsonb NOT NULL DEFAULT '[]'::jsonb,
  started_at timestamptz,
  heartbeat_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kb.job_files (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL REFERENCES kb.ingestion_jobs(id) ON DELETE CASCADE,
  source_path text NOT NULL,
  source_name text NOT NULL,
  byte_size bigint NOT NULL DEFAULT 0 CHECK (byte_size >= 0),
  sha256 text,
  status text NOT NULL DEFAULT 'queued'
    CHECK (status IN ('queued', 'running', 'completed', 'skipped', 'failed')),
  stage text NOT NULL DEFAULT 'queued'
    CHECK (stage IN ('queued', 'parse', 'clean', 'enrich', 'embed', 'index', 'complete')),
  message_count integer NOT NULL DEFAULT 0 CHECK (message_count >= 0),
  chunk_count integer NOT NULL DEFAULT 0 CHECK (chunk_count >= 0),
  embedded_chunks integer NOT NULL DEFAULT 0 CHECK (embedded_chunks >= 0),
  warning_count integer NOT NULL DEFAULT 0 CHECK (warning_count >= 0),
  error text,
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (job_id, source_path)
);

CREATE TABLE IF NOT EXISTS kb.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id bigint NOT NULL REFERENCES kb.sources(id) ON DELETE CASCADE,
  source_ordinal integer NOT NULL CHECK (source_ordinal >= 0),
  stable_id text NOT NULL,
  thread_key text NOT NULL,
  subject_raw text NOT NULL DEFAULT '',
  subject_normalized text NOT NULL DEFAULT '',
  author_raw text NOT NULL DEFAULT '',
  author_display text NOT NULL DEFAULT '',
  author_email_hash text,
  date_raw text NOT NULL DEFAULT '',
  message_date timestamptz,
  body_raw text NOT NULL,
  body_new text NOT NULL DEFAULT '',
  quoted_history text NOT NULL DEFAULT '',
  signature_text text NOT NULL DEFAULT '',
  clean_text text NOT NULL DEFAULT '',
  start_offset bigint NOT NULL CHECK (start_offset >= 0),
  end_offset bigint NOT NULL CHECK (end_offset >= start_offset),
  start_line integer NOT NULL CHECK (start_line > 0),
  end_line integer NOT NULL CHECK (end_line >= start_line),
  relevance text NOT NULL DEFAULT 'unknown'
    CHECK (relevance IN ('technical', 'administrative', 'mixed', 'unknown')),
  summary text NOT NULL DEFAULT '',
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  parser_warnings jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, source_ordinal),
  UNIQUE (source_id, stable_id)
);

CREATE TABLE IF NOT EXISTS kb.chunks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id bigint NOT NULL REFERENCES kb.sources(id) ON DELETE CASCADE,
  message_id bigint NOT NULL REFERENCES kb.messages(id) ON DELETE CASCADE,
  chunk_index integer NOT NULL CHECK (chunk_index >= 0),
  subject text NOT NULL DEFAULT '',
  content text NOT NULL,
  contextual_content text NOT NULL,
  content_sha256 text NOT NULL CHECK (length(content_sha256) = 64),
  approx_tokens integer NOT NULL CHECK (approx_tokens > 0),
  start_offset bigint NOT NULL CHECK (start_offset >= 0),
  end_offset bigint NOT NULL CHECK (end_offset >= start_offset),
  embedding vector(1024),
  embedding_model text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  search_vector tsvector GENERATED ALWAYS AS (
    setweight(to_tsvector('simple'::regconfig, coalesce(subject, '')), 'A') ||
    setweight(to_tsvector('simple'::regconfig, coalesce(contextual_content, '')), 'B') ||
    setweight(to_tsvector('simple'::regconfig, coalesce(content, '')), 'C')
  ) STORED,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (message_id, chunk_index, content_sha256)
);

CREATE TABLE IF NOT EXISTS kb.query_traces (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question text NOT NULL,
  answer_model text,
  embedding_model text,
  retrieved_chunk_ids bigint[] NOT NULL DEFAULT '{}',
  cited_chunk_ids bigint[] NOT NULL DEFAULT '{}',
  abstained boolean NOT NULL DEFAULT false,
  retrieval_ms integer,
  generation_ms integer,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS kb_sources_status_idx ON kb.sources (status, updated_at DESC);
CREATE INDEX IF NOT EXISTS kb_jobs_status_idx ON kb.ingestion_jobs (status, created_at DESC);
CREATE INDEX IF NOT EXISTS kb_job_files_job_status_idx ON kb.job_files (job_id, status, id);
CREATE INDEX IF NOT EXISTS kb_messages_source_idx ON kb.messages (source_id, source_ordinal);
CREATE INDEX IF NOT EXISTS kb_messages_thread_idx ON kb.messages (thread_key, message_date);
CREATE INDEX IF NOT EXISTS kb_chunks_source_idx ON kb.chunks (source_id);
CREATE INDEX IF NOT EXISTS kb_chunks_message_idx ON kb.chunks (message_id, chunk_index);
CREATE INDEX IF NOT EXISTS kb_chunks_search_gin ON kb.chunks USING gin (search_vector);
CREATE INDEX IF NOT EXISTS kb_chunks_subject_trgm ON kb.chunks USING gin (subject gin_trgm_ops);
CREATE INDEX IF NOT EXISTS kb_chunks_content_trgm ON kb.chunks USING gin (content gin_trgm_ops);
CREATE INDEX IF NOT EXISTS kb_chunks_embedding_hnsw
  ON kb.chunks USING hnsw (embedding vector_cosine_ops)
  WITH (m = 16, ef_construction = 64)
  WHERE embedding IS NOT NULL;

INSERT INTO kb.schema_migrations (version, description)
VALUES (1, 'Initial knowledge base, ingestion, pgvector, and hybrid search schema')
ON CONFLICT (version) DO NOTHING;
`;
